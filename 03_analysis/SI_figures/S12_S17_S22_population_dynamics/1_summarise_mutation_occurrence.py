"""
Which residues carried mutations in each round, from the nanopore variant pool.

The collapsed nanopore table lists every distinct amino-acid variant seen across the five
CHX/CPA rounds with a per-round occurrence count. Splitting it by round gives the set of
variants present in that round: 219, 190, 427, 235 and 549. Each variant is counted once,
whatever its read count, so what comes out is the share of the round's distinct variants
that carry a given substitution, not a share of reads.

For each round this writes one row per position and one column per replacement residue,
plus a stacked bar of the same numbers, and it collects the per-position totals for all
five rounds into a single table that 2_ reads.

The summary table this produces was, in the original analysis, generated by a block of
population_dynamics.py that had been commented out with a triple-quoted string, so the
plotting script downstream of it ran off a CSV nobody could regenerate. That block is
what this script restores.

Positions run 1-291; position 292 is the stop codon and is left out, as it was originally.

Outputs, written next to this script:
    mutation_share_per_position.csv
    variant_statistics.csv
    mutation_share_per_residue_round{1..5}.csv
    mutation_share_per_residue_round{1..5}.svg / .png
"""

import ast
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR
while not (REPO_ROOT / ".project-root").exists():
    REPO_ROOT = REPO_ROOT.parent
sys.path.insert(0, str(REPO_ROOT))

from repo_paths import COLLAPSED_UNIQUE_VARIANTS_CSV  # noqa: E402

ROUNDS = (1, 2, 3, 4, 5)
POSITIONS = tuple(range(1, 292))
MAX_MUTATIONS_REPORTED = 12

RESIDUE_COLOURS = {
    "A": "lawngreen", "C": "royalblue", "D": "gainsboro", "E": "mediumpurple",
    "F": "orangered", "G": "gold", "H": "aquamarine", "I": "hotpink",
    "K": "lightseagreen", "L": "olive", "M": "navy", "N": "maroon",
    "P": "lightskyblue", "Q": "darkviolet", "R": "coral", "S": "gray",
    "T": "pink", "V": "forestgreen", "W": "crimson", "Y": "goldenrod",
}

plt.rcParams["svg.fonttype"] = "none"  # keep SVG text editable


def round_variants(collapsed, round_number):
    """The distinct variants present in one round, as the collapsed table records them."""
    return collapsed[collapsed[f"round_{round_number}"] > 0].reset_index(drop=True)


def parse_mutations(value):
    """The aa_mutations cell as a list of (wild-type, position, replacement) triples."""
    if not isinstance(value, str) or value in ("frameshift", "no_translation"):
        return None
    return ast.literal_eval(value)


def count_round(variants):
    """Per-position residue counts and the variant tally for one round."""
    counts = {}
    tally = {"variants": len(variants), "wild_type": 0, "frameshift": 0,
             "no_translation": 0, "premature_stop": 0, "mutations": 0}
    tally.update({f"variants_with_{n}_mutations": 0
                  for n in range(1, MAX_MUTATIONS_REPORTED + 1)})

    for value in variants["aa_mutations"]:
        if value == "frameshift":
            tally["frameshift"] += 1
            continue
        if value == "no_translation":
            tally["no_translation"] += 1
            continue

        mutations = parse_mutations(value) or []
        if not mutations:
            tally["wild_type"] += 1
            continue
        if len(mutations) <= MAX_MUTATIONS_REPORTED:
            tally[f"variants_with_{len(mutations)}_mutations"] += 1

        for wild_type_residue, position, replacement in mutations:
            position = int(position) if position else 0
            if replacement == "*":
                tally["premature_stop"] += 1
                replacement = "premature stop codon"
            elif not replacement.strip():
                tally["wild_type"] += 1
                replacement = "WT"
            counts.setdefault(position, {}).setdefault(replacement, 0)
            counts[position][replacement] += 1

    tally["mutations"] = sum(sum(residues.values()) for residues in counts.values())
    return counts, tally


def shares(counts, total_variants):
    """Counts as a percentage of the round's variants, one row per position."""
    rows = [{residue: value / total_variants * 100
             for residue, value in counts.get(position, {}).items()}
            for position in POSITIONS]
    return pd.DataFrame(rows, index=pd.Index(POSITIONS, name="Position"))


def plot_round(table, round_number):
    """Stacked bar of the per-residue shares along the sequence."""
    colours = [RESIDUE_COLOURS.get(column, "black") for column in table.columns]
    ax = table.plot(kind="bar", stacked=True, figsize=(15, 5), color=colours, width=0.8)
    ax.set_xlabel("Amino acid position")
    ax.set_ylabel("Share of round's variants carrying the mutation (%)")
    ax.set_xticks(np.arange(-1, 290, step=5))
    ax.set_xticklabels(np.arange(0, 292, step=5))
    ax.set_ylim(0, 100)
    ax.set_yticks(np.arange(0, 101, step=5))
    ax.set_title(f"Round {round_number}")

    handles, labels = ax.get_legend_handles_labels()
    handles, labels = zip(*sorted(zip(handles, labels), key=lambda pair: pair[1]))
    ax.legend(handles, labels, loc="center left", bbox_to_anchor=(1, 0.5))

    figure = ax.get_figure()
    for extension in ("svg", "png"):
        figure.savefig(THIS_DIR / f"mutation_share_per_residue_round{round_number}.{extension}",
                       dpi=400, bbox_inches="tight")
    plt.close(figure)


def main():
    collapsed = pd.read_csv(COLLAPSED_UNIQUE_VARIANTS_CSV)
    summary = pd.DataFrame({"Position": POSITIONS})
    tallies = []

    for round_number in ROUNDS:
        variants = round_variants(collapsed, round_number)
        counts, tally = count_round(variants)
        table = shares(counts, len(variants))

        table.to_csv(THIS_DIR / f"mutation_share_per_residue_round{round_number}.csv")
        plot_round(table, round_number)

        summary[f"round_{round_number}"] = table.sum(axis=1).to_numpy()
        tallies.append({"round": round_number, **tally})
        print(f"round {round_number}: {tally['variants']} variants, "
              f"{tally['mutations']} mutations over "
              f"{(table.sum(axis=1) > 0).sum()} positions")

    summary.to_csv(THIS_DIR / "mutation_share_per_position.csv", index=False)
    pd.DataFrame(tallies).to_csv(THIS_DIR / "variant_statistics.csv", index=False)


if __name__ == "__main__":
    main()
